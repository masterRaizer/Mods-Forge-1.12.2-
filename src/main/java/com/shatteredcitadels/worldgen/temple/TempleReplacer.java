package com.shatteredcitadels.worldgen.temple;

import com.shatteredcitadels.ShatteredCitadelsMod;
import com.shatteredcitadels.config.ConfigCache;
import net.minecraft.world.gen.MapGenBase;
import net.minecraft.world.gen.structure.MapGenScatteredFeature;
import net.minecraftforge.event.terraingen.InitMapGenEvent;
import net.minecraftforge.fml.common.eventhandler.SubscribeEvent;

/** Installs {@link ScatteredFeatureGen}; registered on {@code MinecraftForge.TERRAIN_GEN_BUS} by the common proxy. */
public final class TempleReplacer {

    private TempleReplacer() {
    }

    @SubscribeEvent
    public static void onInitMapGen(InitMapGenEvent event) {
        if (event.getType() != InitMapGenEvent.EventType.SCATTERED_FEATURE
                || !ConfigCache.get().isReplaceDesertTemples() && !ConfigCache.get().isReplaceJungleTemples()
                && !ConfigCache.get().isWitchHutsEnabled()) {
            return;
        }
        MapGenBase gen = event.getNewGen();
        if (gen != null && gen.getClass() == MapGenScatteredFeature.class) {
            event.setNewGen(new ScatteredFeatureGen(VanillaTempleSites.INSTANCE, 32));
            return;
        }
        if (gen instanceof MapGenScatteredFeature) {
            BopTempleSites bop = BopTempleSites.from((MapGenScatteredFeature) gen);
            if (bop != null) {
                ShatteredCitadelsMod.LOGGER.info("Biomes O' Plenty temples: our temples take its desert and jungle sites");
                event.setNewGen(new ScatteredFeatureGen(bop, BopTempleSites.spacingOf((MapGenScatteredFeature) gen)));
                return;
            }
        }
        // Another mod's replacement (or a subclass with its own rules) is left alone.
        ShatteredCitadelsMod.LOGGER.info("Scattered features are generated by {}; its temples stay",
                gen == null ? "nothing" : gen.getClass().getName());
    }
}
